"""Registry contract enforcement — see docs/DESIGN.md §3.2.

This module implements `gpufluid blocks --check`. It runs 6 checks:

  1. ID format (re-verified at check time)
  2. Layer declared in DESIGN.md §§4-11
  3. BLOCKS.md row count matches registry
  4. No cross-layer import violations (AST scan)
  5. No duplicate (id, qualname) pairs
  6. Every block has a guard test (warning only)

The folder→layer map and the declared-layer set are PARSED from
DESIGN.md (§2.1 code block, §§4-11 headings) so there is exactly one
source of truth.
"""
from __future__ import annotations
import ast
import importlib
import re
import sys
from dataclasses import dataclass, field
from pathlib import Path
from typing import Dict, List, Set, Tuple

from . import BlockInfo, get_registry, _BLOCK_ID_RE

